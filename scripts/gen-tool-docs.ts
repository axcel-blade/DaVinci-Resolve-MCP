/** Generates docs/TOOLS.md from the live tool registry (names, schemas, support level, kind). Run: pnpm docs:tools */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { PROJECT_ROOT } from "../src/config/constants.js";
import { buildRegistry } from "../src/mcp/tools/index.js";
import type { RegisteredTool } from "../src/mcp/tools/registry.js";
import { zodToJsonSchema } from "../src/utils/zod-json.js";

const reg = buildRegistry();
const MODULE_TITLES: Record<string, string> = {
  application: "1. Application", projects: "2. Projects", media: "3. Media", timeline: "4. Timeline", editing: "5. Editing",
  effects: "6. Effects & transitions", speed: "7. Speed", titles: "8. Titles", subtitles: "9. Subtitles", fusion: "10. Fusion",
  color: "11. Color", audio: "12. Fairlight audio", ai: "13. AI", photo: "14. Photo page", rendering: "15. Rendering",
  workflows: "16. Workflows", meta: "17. Background jobs & meta",
};
const SUPPORT: Record<string, string> = {
  api: "Resolve scripting API", fusion: "Fusion scripting", integration: "Resolve API + FFmpeg / files", external: "external AI provider",
  planner: "server-side planner / workflow", unsupported: "unsupported (returns `UNSUPPORTED` with an alternative)",
};

function example(schema: Record<string, unknown>): Record<string, unknown> {
  const props = (schema.properties ?? {}) as Record<string, Record<string, unknown>>;
  const req = (schema.required ?? []) as string[];
  const out: Record<string, unknown> = {};
  for (const k of req) {
    const p = props[k]!;
    if (p.enum) out[k] = (p.enum as unknown[])[0];
    else if (p.type === "number" || p.type === "integer") out[k] = (p.minimum as number) > 0 ? p.minimum : 1;
    else if (p.type === "string") out[k] = /path|folder|dir|file/i.test(k) ? "C:\\Users\\you\\Videos\\example.mp4" : k.toLowerCase().includes("color") ? "#1A2B3C" : "Example";
    else if (p.type === "boolean") out[k] = true;
    else if (p.type === "array") out[k] = [];
    else out[k] = {};
  }
  return out;
}

const byModule = new Map<string, RegisteredTool[]>();
for (const t of reg.tools.values()) (byModule.get(t.category) ?? byModule.set(t.category, []).get(t.category)!).push(t);

const counts = { supported: 0, unsupported: 0, provider: 0 };
for (const t of reg.tools.values()) {
  if (t.support === "unsupported") counts.unsupported++;
  else if (t.support === "external") counts.provider++;
  else counts.supported++;
}

let md = `# MCP Tools Reference

_Generated by \`pnpm docs:tools\` from the live catalog — do not edit by hand._

**${reg.tools.size} tools**: ${counts.supported} supported, ${counts.provider} require an external AI provider, ${counts.unsupported} unsupported (return \`UNSUPPORTED\` with an alternative).

## Common output schema

Every tool returns one text content block containing JSON, also sent as \`structuredContent\`:

\`\`\`json
{ "ok": true, "tool": "<name>", "source": "resolve | mock | server", "status": "ok", "message": "...", "data": { "...tool specific..." }, "warnings": ["..."] }
\`\`\`

Errors set \`isError: true\` and return \`{ "ok": false, "tool": "<name>", "status": "error", "message": "...", "error": { "code": "OPERATION_FAILED", "message": "...", "details": {}, "hint": "..." } }\`.
\`status\` is one of ok, partial, unsupported, error, confirmation_required.
Codes: VALIDATION_ERROR, CONFIRMATION_REQUIRED, RESOLVE_NOT_INSTALLED, RESOLVE_NOT_RUNNING, SCRIPTING_UNAVAILABLE, PYTHON_NOT_FOUND, NO_PROJECT, NO_TIMELINE, NOT_FOUND, AMBIGUOUS, ALREADY_EXISTS, PATH_NOT_ALLOWED, FILE_EXISTS, OPERATION_FAILED, UNSUPPORTED, TIMEOUT, BRIDGE_BUSY, BRIDGE_CRASHED, UNKNOWN_OP, RENDER_FAILED, PROVIDER_NOT_CONFIGURED, PROVIDER_ERROR.

**Addressing.** Timeline items are addressed by \`itemId\` (from \`timeline_get_clips\`) or \`trackType\` + \`trackIndex\` + \`itemIndex\` (1-based, clips only). Frames are integers; absolute timeline frames include the timeline start.

**Permissions.** Read-only tools need nothing beyond a reachable DaVinci Resolve (external scripting set to Local). Write tools need an open project (unless they create one). Tools that write files need the path inside \`ALLOWED_WRITE_PATHS\`. Destructive tools need \`confirm: true\`. AI-provider tools need provider credentials and network access.

`;
for (const [mod, tools] of byModule) {
  md += `\n## ${MODULE_TITLES[mod] ?? mod}\n`;
  for (const t of tools) {
    const schema = zodToJsonSchema(t.inputSchema);
    const kind = t.readOnly ? "read-only" : t.destructive ? "destructive (confirm: true)" : t.support === "external" ? "external service" : "write";
    md += `\n### \`${t.name}\`\n\n${t.description}\n\n`;
    md += `- **Status:** ${t.support === "unsupported" ? "unsupported" : t.support === "external" ? "requires_provider" : "supported"}\n- **Kind:** ${kind}\n`;
    md += `- **Implementation:** ${SUPPORT[t.support] ?? t.support}\n`;
    md += `\n<details><summary>Input schema</summary>\n\n\`\`\`json\n${JSON.stringify(schema, null, 2)}\n\`\`\`\n</details>\n\nExample: \`${JSON.stringify({ name: t.name, arguments: example(schema) })}\`\n`;
  }
}
writeFileSync(join(PROJECT_ROOT, "docs", "TOOLS.md"), md);
console.log(`docs/TOOLS.md: ${reg.tools.size} tools`);
